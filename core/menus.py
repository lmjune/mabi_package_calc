def candidates(time="점심", solo=False, kind=None, max_price=3, exclude=()):
    """조건에 맞는 메뉴 목록"""
    ex = [e.strip() for e in exclude if e.strip()]
    out = []
    for name, k, price, t, is_solo in MENUS:
        if t != "둘다" and t != time:
            continue
        if solo and not is_solo:
            continue
        if kind and k != kind:
            continue
        if price > max_price:
            continue
        if any(e in name for e in ex):
            continue
        variants = [v for v in VARIANTS.get(name, []) if not any(e in v for e in ex)]
        if VARIANTS.get(name) and not variants:      # 세부 메뉴가 전부 제외되면 이 메뉴도 제외
            continue
        out.append({"name": name, "kind": k, "price": price, "solo": is_solo, "variants": variants})
    return out


def pick(n=1, avoid=(), **cond):
    """조건에 맞는 메뉴 n개를 겹치지 않게 뽑기. avoid: 방금 나온 메뉴는 가급적 빼기"""
    pool = candidates(**cond)
    fresh = [m for m in pool if m["name"] not in avoid]
    src = fresh if len(fresh) >= n else pool
    picked = random.sample(src, min(n, len(src)))
    for m in picked:                                  # 세부 메뉴까지 고르기
        m["detail"] = random.choice(m["variants"]) if m["variants"] else None
        m["show"] = f"{m['detail']}" if m["detail"] else m["name"]
    return picked